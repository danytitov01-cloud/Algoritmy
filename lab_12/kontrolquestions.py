# Что такое хеширование?
# Хеширование это способ быстрого поиска данных по ключу с помощью преобразования ключа в индекс.

# Что такое хеш-функция?
# Хеш-функция это функция, которая преобразует ключ в число (индекс).

# Что называется коллизией?
# Коллизия это ситуация, когда разные ключи дают один и тот же индекс.

# Какие операции поддерживает хеш-таблица?
# Добавление, поиск и удаление элементов.

# Почему словарь Python считается примером хеш-таблицы?
# Потому что он хранит данные в формате ключ-значение и использует хеширование.

# Что такое ключ и значение?
# Ключ это уникальный идентификатор, значение — это данные, связанные с ключом.

# В чем преимущество хеширования перед линейным поиском?
# Хеширование работает быстрее, обычно за O(1), а линейный поиск — за O(n).

# Какие методы разрешения коллизий существуют?
# Метод цепочек (списки) и открытая адресация.